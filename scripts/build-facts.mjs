// Writes api/_facts.js: the notebook's text that the sticky note answers from, read out of index.html.
// Run it after editing the site's text:   node scripts/build-facts.mjs
// It opens the page in headless Chrome (no npm packages needed) and copies what the page itself builds as FACTS,
// so the server always answers from the same words visitors see. The page and the server each fingerprint the facts;
// if you forget to rerun this, the server keeps answering from the old copy and notes it in the Vercel logs.
import { execFileSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const chrome = process.env.CHROME_PATH || [
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'
].find(existsSync);
if (!chrome) { console.error('Could not find Chrome. Set CHROME_PATH to your Chrome or Chromium binary.'); process.exit(1); }

const url = pathToFileURL(path.join(root, 'index.html')).href + '?facts';
const dom = execFileSync(chrome, ['--headless=new', '--disable-gpu', '--virtual-time-budget=4000', '--dump-dom', url],
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] });

const m = dom.match(/<script type="application\/json" id="factsOut">([\s\S]*?)<\/script>/);
if (!m) { console.error('The page did not export its facts. Is the ?facts hook still in index.html?'); process.exit(1); }
const data = JSON.parse(m[1]);
if (!data.facts || data.facts.length < 1000) { console.error('The exported facts look empty; not writing.'); process.exit(1); }

const out = '// Generated by scripts/build-facts.mjs from index.html. Do not edit by hand: change the site, then rerun the script.\n' +
  'export default ' + JSON.stringify(data, null, 1) + ';\n';
writeFileSync(path.join(root, 'api', '_facts.js'), out);
console.log(`api/_facts.js written: ${data.facts.length.toLocaleString()} characters, ${data.pages.length} pages, fingerprint ${data.v}`);
